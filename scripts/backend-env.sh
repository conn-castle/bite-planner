#!/usr/bin/env bash
# Writes backend/.env for the Neon dev branch (run through `make env`). DATABASE_URL
# comes from AWS SSM, the source of truth for secrets (docs/operations/aws.md "Secrets"); the Neon
# Auth URL from apps/mobile/.env.development. The secret never reaches a command line.
set -euo pipefail
cd "$(dirname "$0")/.."

auth_url=$(sed -n 's/^VITE_NEON_AUTH_URL=//p' apps/mobile/.env.development)
[[ -n $auth_url ]] || { echo "VITE_NEON_AUTH_URL missing from apps/mobile/.env.development" >&2; exit 1; }

umask 077
tmp=$(mktemp backend/.env.XXXXXX)
trap 'rm -f "$tmp"' EXIT
{
  echo '# Neon dev branch. Generated by `make env` from AWS SSM (profile conn); see docs/operations/aws.md "Secrets".'
  printf 'DATABASE_URL='
  aws ssm get-parameter --profile conn --region us-east-1 --with-decryption \
    --name /castle-chef/development/database-url --query Parameter.Value --output text
  echo "CASTLE_CHEF_NEON_AUTH_URL=$auth_url"
  echo "CASTLE_CHEF_JOB_DISPATCH=local"
} >"$tmp"
mv "$tmp" backend/.env
echo "Wrote backend/.env (Neon dev)."
